#pragma once
#include "xlat.h"

#define INTR_FLAGS_ENDS_RUN (1u << 0)
#define INTR_FLAGS_WRITE_PC (1u << 1)
#define INTR_FLAGS_TODO     (1u << 2)

#define INTR_OPERATION_DATA_OPS 0
#define INTR_OPERATION_MULTIPLY 1

#define INTR_SHFT_SRC_IMM 0
#define INTR_SHFT_SRC_REG 1

#define INTR_SHFT_TYPE_LSL 0
#define INTR_SHFT_TYPE_LSR 1
#define INTR_SHFT_TYPE_ASR 2
#define INTR_SHFT_TYPE_ROR 3

// intermediate form
struct intr {
    uint8_t insn_sz;
    uint32_t flags;

    uint8_t condition;
    uint8_t operation;
    uint8_t opcode;
    uint8_t set_flags;
    uint8_t dest_reg;
    uint8_t srcm_reg;
    uint8_t srcn_reg;
    uint8_t accm_reg;
    uint8_t shft_reg;
    uint8_t shft_imm;
    uint8_t shft_src;
    uint8_t shft_type;
};

#define ARM_FAMILY_SHFT         25
#define ARM_FAMILY_MASK         7
#define ARM_FAMILY_DATA_OPS_REG 0
#define ARM_FAMILY_DATA_OPS_IMM 1
#define ARM_FAMILY_DATA_MOV_IMM 2
#define ARM_FAMILY_DATA_MOV_REG 3
#define ARM_FAMILY_DATA_MOV_MUL 4
#define ARM_FAMILY_BRANCH       5
#define ARM_FAMILY_DATA_MOV_COP 6
#define ARM_FAMILY_OTHER        7

/* ARM FAMILY: DATA OPS REGISTER */

#define ARM_DATA_OPS_REG_OPCODE_SHFT 21
#define ARM_DATA_OPS_REG_OPCODE_MASK 0xF
#define ARM_DATA_OPS_REG_OPCODE_AND  0x0
#define ARM_DATA_OPS_REG_OPCODE_EOR  0x1
#define ARM_DATA_OPS_REG_OPCODE_SUB  0x2
#define ARM_DATA_OPS_REG_OPCODE_RSB  0x3
#define ARM_DATA_OPS_REG_OPCODE_ADD  0x4
#define ARM_DATA_OPS_REG_OPCODE_ADC  0x5
#define ARM_DATA_OPS_REG_OPCODE_SBC  0x6
#define ARM_DATA_OPS_REG_OPCODE_RSC  0x7
#define ARM_DATA_OPS_REG_OPCODE_TST  0x8
#define ARM_DATA_OPS_REG_OPCODE_TEQ  0x9
#define ARM_DATA_OPS_REG_OPCODE_CMP  0xA
#define ARM_DATA_OPS_REG_OPCODE_CMN  0xB
#define ARM_DATA_OPS_REG_OPCODE_ORR  0xC
#define ARM_DATA_OPS_REG_OPCODE_MOV  0xD
#define ARM_DATA_OPS_REG_OPCODE_BIC  0xE
#define ARM_DATA_OPS_REG_OPCODE_MVN  0xF

#define ARM_DATA_OPS_REG_SET_FLAGS_SHFT 20
#define ARM_DATA_OPS_REG_SET_FLAGS_MASK 1

#define ARM_DATA_OPS_REG_SRCN_REG_SHFT 16
#define ARM_DATA_OPS_REG_SRCN_REG_MASK 0xF

#define ARM_DATA_OPS_REG_DEST_REG_SHFT 12
#define ARM_DATA_OPS_REG_DEST_REG_MASK 0xF

#define ARM_DATA_OPS_REG_SHFT_REG_SHFT 8
#define ARM_DATA_OPS_REG_SHFT_REG_MASK 0xF

#define ARM_DATA_OPS_REG_SHFT_IMM_SHFT 7
#define ARM_DATA_OPS_REG_SHFT_IMM_MASK 0x1F

#define ARM_DATA_OPS_REG_SHFT_TYPE_SHFT 5
#define ARM_DATA_OPS_REG_SHFT_TYPE_MASK 3
#define ARM_DATA_OPS_REG_SHFT_TYPE_LSL  0
#define ARM_DATA_OPS_REG_SHFT_TYPE_LSR  1
#define ARM_DATA_OPS_REG_SHFT_TYPE_ASR  2
#define ARM_DATA_OPS_REG_SHFT_TYPE_ROR  3
#define ARM_DATA_OPS_REG_SHFT_TYPE_RRX  4 // added for convenience

#define ARM_DATA_OPS_REG_SHFT_SRC_SHFT 4
#define ARM_DATA_OPS_REG_SHFT_SRC_MASK 1
#define ARM_DATA_OPS_REG_SHFT_SRC_IMM  0
#define ARM_DATA_OPS_REG_SHFT_SRC_REG  1

#define ARM_DATA_OPS_REG_SRCM_REG_SHFT 0
#define ARM_DATA_OPS_REG_SRCM_REG_MASK 0xF

/* ARM FAMILY: DATA OPS REGISTER - EXCEPTION: MULTIPLY */

#define ARM_DATA_OPS_REG_MULT_BITS (0b1001 << ARM_DATA_OPS_REG_SHFT_SRC_SHFT)
#define ARM_DATA_OPS_REG_MULT_MASK (0b1111 << ARM_DATA_OPS_REG_SHFT_SRC_SHFT)

#define ARM_DATA_OPS_REG_MULT_OPCODE_SHFT  21
#define ARM_DATA_OPS_REG_MULT_OPCODE_MASK  7
#define ARM_DATA_OPS_REG_MULT_OPCODE_MUL   0
#define ARM_DATA_OPS_REG_MULT_OPCODE_MLA   1
#define ARM_DATA_OPS_REG_MULT_OPCODE_UMAAL 2
#define ARM_DATA_OPS_REG_MULT_OPCODE_MLS   3
#define ARM_DATA_OPS_REG_MULT_OPCODE_UMULL 4
#define ARM_DATA_OPS_REG_MULT_OPCODE_UMLAL 5
#define ARM_DATA_OPS_REG_MULT_OPCODE_SMULL 6
#define ARM_DATA_OPS_REG_MULT_OPCODE_SMLAL 7

#define ARM_DATA_OPS_REG_MULT_SET_FLAGS_SHFT 20
#define ARM_DATA_OPS_REG_MULT_SET_FLAGS_MASK 1

#define ARM_DATA_OPS_REG_MULT_DEST_REG_SHFT 16
#define ARM_DATA_OPS_REG_MULT_DEST_REG_MASK 0xF

#define ARM_DATA_OPS_REG_MULT_ACCM_REG_SHFT 12
#define ARM_DATA_OPS_REG_MULT_ACCM_REG_MASK 0xF

#define ARM_DATA_OPS_REG_MULT_SHFT_REG_SHFT 8
#define ARM_DATA_OPS_REG_MULT_SHFT_REG_MASK 0xF

#define ARM_DATA_OPS_REG_MULT_SRCM_REG_SHFT 0
#define ARM_DATA_OPS_REG_MULT_SRCM_REG_MASK 0xF

/* ARM FAMILY: DATA OPS REGISTER - EXCEPTION: MISCELLANEOUS */

#define ARM_DATA_OPS_REG_MISC_BITS ((0b1000 << ARM_DATA_OPS_REG_OPCODE_SHFT) | (0 << ARM_DATA_OPS_REG_SET_FLAGS_SHFT))
#define ARM_DATA_OPS_REG_MISC_MASK ((0b1100 << ARM_DATA_OPS_REG_OPCODE_SHFT) | (1 << ARM_DATA_OPS_REG_SET_FLAGS_SHFT))

struct intr *decode(struct mm *mm, struct xlat *xlat, gmeta_t gmeta, struct hargs *hargs);
